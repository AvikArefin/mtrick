import os
import re
import sys
import json
import time
import atexit
import subprocess
from datetime import datetime
from typing import Any

# Every record gets this wall-clock key; '_'-prefixed keys are metadata and aren't plotted.
TIME_KEY = "_time"


def _flatten(d: dict, prefix: str = "") -> dict:
    """{'optim': {'lr': 0.1}} -> {'optim.lr': 0.1}"""
    out = {}
    for k, v in d.items():
        key = f"{prefix}{k}"
        if isinstance(v, dict):
            out.update(_flatten(v, f"{key}."))
        else:
            out[key] = v
    return out


class Tracker:
    def __init__(
        self,
        experiment_name: str,
        save_path: str = "metrics",
        note: str | None = None,
        config: dict[str, Any] | None = None,
        system_metrics: bool = False,
        group: str | None = None,
        require_clean: bool = True,
    ):
        """
        config: hyperparameters/settings saved to config.json (nested dicts are flattened to 'a.b' keys).
        system_metrics: also log process memory (and CUDA memory if torch is in use) with every log() call.
        group: runs that belong together (e.g. a model version); prefixes the run directory so they sort together.
        require_clean: refuse to start unless every change is committed, so git_commit is exactly the code that ran.
            Pass False to track anyway, e.g. outside a git repository; a dirty commit is then marked with '*'.
        """
        if group is not None and not re.fullmatch(r"[A-Za-z0-9.-]+", group):
            raise ValueError(f"group may only contain letters, digits, '.' and '-', got {group!r}")

        self.experiment_name = experiment_name
        self.save_path = save_path
        self.system_metrics = system_metrics
        self.group = group

        # Autogenerated metadata
        self.start_time: float = time.time()
        self.timestamp: str = datetime.fromtimestamp(self.start_time).strftime("%Y%m%d_%H%M%S")
        self.git_commit: str = self.get_git_commit()
        if require_clean and (self.git_commit == "unknown" or self.git_commit.endswith("*")):
            raise RuntimeError(
                "not in a git repository, so the code that ran can't be recorded" if self.git_commit == "unknown" else
                "commit your changes first (git status lists them); "
                f"files under {self.save_path!r} don't count"
                + ". Or pass require_clean=False to track anyway."
            )

        # Determine experiment number from the highest existing exp* directory
        os.makedirs(self.save_path, exist_ok=True)
        self.experiment_number = self.get_experiment_number()

        dir_name = f"exp{self.experiment_number:03d}_{self.experiment_name}_{self.timestamp}"
        if self.group is not None:
            dir_name = f"{self.group}_{dir_name}"
        self.experiment_dir = os.path.join(self.save_path, dir_name)
        try:
            os.mkdir(self.experiment_dir)
        except FileExistsError:
            raise RuntimeError(
                f"Failed to create a unique run directory {self.save_path}"
            )

        # Metadata dump
        self.meta = {
            "experiment_name": self.experiment_name,
            "experiment_number": self.experiment_number,
            "timestamp": self.timestamp,
            "git_commit": self.git_commit,
        }
        if self.group is not None:
            self.meta["group"] = self.group
        with open(os.path.join(self.experiment_dir, "meta.json"), "w") as f:
            json.dump(self.meta, f, indent=4)

        if note is not None:
            with open(os.path.join(self.experiment_dir, "note.txt"), "w") as f:
                f.write(note)

        if config is not None:
            with open(os.path.join(self.experiment_dir, "config.json"), "w") as f:
                json.dump(_flatten(config), f, indent=4, default=str)

        # Run status: 'running' until the process ends, then 'finished', 'crashed' or 'interrupted'.
        # A run killed by the OS (OOM, SIGKILL, preemption) stays 'running'; xscope spots it from stale timestamps.
        self._finished = False
        self._write_status("running")
        self._previous_excepthook = sys.excepthook
        sys.excepthook = self._excepthook
        atexit.register(self.finish)

        print(f"Tracking experiment at: {self.experiment_dir}")

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc, tb):
        if exc_type is None:
            self.finish()
        else:
            self.finish(self._status_for(exc_type), error=f"{exc_type.__name__}: {exc}")
        return False

    def get_git_commit(self) -> str:
        """
        Returns the current short git commit hash, appending '*' if uncommitted changes exist.
        Changes under save_path don't count: those are earlier runs' logs, not code.
        """
        def git(*args: str) -> str:
            return subprocess.check_output(["git", *args], stderr=subprocess.DEVNULL).decode("utf-8").strip()

        try:
            commit_hash = git("rev-parse", "--short", "HEAD")
            try:
                status = git("status", "--porcelain", "--", ":/", f":(exclude){self.save_path}")
            except subprocess.CalledProcessError:
                status = git("status", "--porcelain")   # save_path is outside the repository
            if status:
                return f"{commit_hash}*"
            return commit_hash
        except Exception:
            return "unknown"

    def get_experiment_number(self) -> int:
        max_exp_num = 0
        for path in os.listdir(self.save_path):
            match = re.match(r"^(?:[A-Za-z0-9.-]+_)?exp(\d+)_", path)   # with or without a group prefix
            if match:
                max_exp_num = max(max_exp_num, int(match.group(1)))

        return max_exp_num + 1

    # ------------------------------------------------------------------
    # Run status
    # ------------------------------------------------------------------

    @staticmethod
    def _status_for(exc_type) -> str:
        return "interrupted" if issubclass(exc_type, KeyboardInterrupt) else "crashed"

    def _write_status(self, status: str, error: str | None = None):
        data: dict[str, Any] = {"status": status, "started": self.start_time, "updated": time.time()}
        if error:
            data["error"] = error
        path = os.path.join(self.experiment_dir, "status.json")
        tmp = path + ".tmp"
        try:
            with open(tmp, "w") as f:
                json.dump(data, f, indent=4)
            os.replace(tmp, path)
        except OSError:
            pass  # the run directory may already be gone at interpreter shutdown

    def _excepthook(self, exc_type, exc, tb):
        self.finish(self._status_for(exc_type), error=f"{exc_type.__name__}: {exc}")
        self._previous_excepthook(exc_type, exc, tb)

    def finish(self, status: str = "finished", error: str | None = None):
        """Marks the run as ended. Called automatically at exit; call it yourself in notebooks."""
        if self._finished:
            return
        self._finished = True
        self._write_status(status, error)
        atexit.unregister(self.finish)
        if sys.excepthook == self._excepthook:
            sys.excepthook = self._previous_excepthook

    # ------------------------------------------------------------------
    # Logging
    # ------------------------------------------------------------------

    def _system_snapshot(self) -> dict[str, float]:
        """Peak process memory (stdlib only) and current CUDA memory if torch is already imported."""
        stats: dict[str, float] = {}
        try:
            import resource  # Unix only
            peak = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
            # ru_maxrss is in bytes on macOS and kilobytes on Linux
            stats["sys/peak_rss_gb"] = peak / (1024 ** 3 if sys.platform == "darwin" else 1024 ** 2)
        except ImportError:
            pass
        torch = sys.modules.get("torch")
        if torch is not None:
            try:
                if torch.cuda.is_available():
                    stats["sys/gpu_mem_gb"] = torch.cuda.memory_allocated() / 1024 ** 3
            except Exception:
                pass
        return stats

    def _append(self, filename: str, record: dict[str, Any]):
        record[TIME_KEY] = time.time()
        with open(os.path.join(self.experiment_dir, filename), "a") as f:
            f.write(json.dumps(record) + "\n")

    def log(
        self,
        metrics: dict[str, float],
        epoch: int,
    ):
        """
        Logs 1D metrics. Useful for loss, accuracy etc curves.
        """
        # 0-d tensors and numpy scalars become plain numbers, which json can store
        metrics = {k: v.item() if hasattr(v, "item") else v for k, v in metrics.items()}
        formatted_metrics = ", ".join(
            f"{k}: {v:.4f}" if isinstance(v, float) else f"{k}: {v}" for k, v in metrics.items()
        )
        print(f"{epoch:4d}| {formatted_metrics}")

        log_entry: dict[str, Any] = {"epoch": epoch, **metrics}
        if self.system_metrics:
            log_entry.update(self._system_snapshot())
        self._append("metrics.jsonl", log_entry)

    def log_text(
        self,
        texts: dict[str, str],
        epoch: int | None = None,
        filename: str = "text.jsonl",
    ):
        """
        Logs short pieces of text, e.g. sample predictions: {"the target": "what the model read"}.
        [visible via xscope library only]
        """
        for key, text in texts.items():
            print(f"    | {key}: {text!r}")

        record: dict[str, Any] = {}
        if epoch is not None:
            record["epoch"] = epoch
        record.update({key: str(text) for key, text in texts.items()})
        self._append(filename, record)

    def log_2d(
        self,
        data: dict[str, list[list[float]]] | None = None,
        epoch: int | None = None,
        filename: str = "2d.jsonl",
        **kwargs: list[list[float]],
    ):
        """
        Logs 2D spatial points/lines to a JSONL file.
        Keys using '/' (e.g., 'data/true', 'data/pred') can be grouped into the same chart.
        [visible via xscope library only]
        """
        merged_data: dict[str, list[list[float]]] = {}
        if data:
            merged_data.update(data)
        if kwargs:
            merged_data.update(kwargs)

        formatted_data: dict[str, Any] = {}
        if epoch is not None:
            formatted_data["epoch"] = epoch

        for key, points in merged_data.items():
            formatted_data[key] = [[float(p[0]), float(p[1])] for p in points]

        self._append(filename, formatted_data)

    def log_matrix(
        self,
        matrix: Any,
        labels: list[str] | None = None,
        step: int | None = None,
        filename: str = "matrix.jsonl",
    ):
        """
        Logs a 2D matrix (e.g. confusion matrix) to a JSONL file.
        matrix: 2D numpy array, PyTorch tensor, or nested list [row][col]
        labels: List of string labels for rows/columns.
        step: Optional evaluation step or epoch index.
        filename: JSONL filename to append matrix records.
        """
        if hasattr(matrix, "tolist"):
            raw_matrix = matrix.tolist()
        else:
            raw_matrix = [list(row) for row in matrix]

        if labels is None:
            labels = [f"Class {i}" for i in range(len(raw_matrix))]

        formatted_data: dict[str, Any] = {}
        if step is not None:
            formatted_data["step"] = step

        formatted_data["labels"] = labels
        formatted_data["matrix"] = raw_matrix

        self._append(filename, formatted_data)

    def log_calibration(
        self,
        confidences: Any,
        correct: Any,
        step: int | None = None,
        bins: int = 10,
        filename: str = "calibration.jsonl",
    ):
        """
        Logs a reliability histogram for calibration analysis (only the bin summaries are stored).
        confidences: the model's confidence in each prediction (e.g. max softmax probability), in [0, 1].
        correct: whether each prediction was right (bools or 0/1), same length as confidences.
        step: Optional evaluation step or epoch index.
        """
        conf = confidences.tolist() if hasattr(confidences, "tolist") else list(confidences)
        hits = correct.tolist() if hasattr(correct, "tolist") else list(correct)
        if len(conf) != len(hits):
            raise ValueError("confidences and correct must have the same length")

        counts = [0] * bins
        conf_sums = [0.0] * bins
        hit_sums = [0.0] * bins
        for c, h in zip(conf, hits):
            c = min(max(float(c), 0.0), 1.0)
            b = min(int(c * bins), bins - 1)
            counts[b] += 1
            conf_sums[b] += c
            hit_sums[b] += float(bool(h))

        record: dict[str, Any] = {}
        if step is not None:
            record["step"] = step
        record["bins"] = [
            {"count": n, "confidence": s / n, "accuracy": a / n}
            for n, s, a in zip(counts, conf_sums, hit_sums) if n
        ]
        self._append(filename, record)
